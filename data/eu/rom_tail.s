@ Leftover block at the end of the European ROM (generated by tools/eu_port/disasm_rom_tail.py),
@ followed by 0xFF padding up to 0x08FFF000 and 0x800 zero bytes. The US ROM is 8 MiB and has
@ none of this, and the game never references it.
@ It is a debug monitor for the development hardware, linked to run from the memory of a 1 Mbit
@ DACS at 0x09FE0000, not where it is in this ROM. The BIOS forwards the FIQ and undefined
@ instruction exceptions to 0x09FE2000 when the cartridge header enables it; the monitor then
@ saves the state of the game and runs the commands that the host writes to MonCommandBlock:
@ read or write memory (through a buffer at 0x09FE3000), single step (with a breakpoint made of
@ an undefined instruction), resume, reset the game, identify, erase and program flash memory,
@ fill memory, call functions of the game.
@ It is made of a resident part (the first 4 KB) at 0x09FE2000 and three overlays (the following
@ 4 KB pages) that its control register (MonControl) maps at 0x09FE3000; each overlay starts
@ with a table of entry points. The names come from what the code does; the other labels are
@ named after their run address, and "label - RES" (or OV1, OV2, OV3) is that address.

	.syntax unified
	.section .rodata

@ resident part, runs at 0x09FE2000

gUnusedRomTailCode:: @ 0x08FE0000
	.set RES, gUnusedRomTailCode - 0x09FE2000

@ The BIOS forwards the FIQ and undefined instruction exceptions here (the debugging
@ handler of a 1 Mbit DACS) when bits 2 and 7 of the header byte at 0x0800009C are set.
MonDebugVectors:
	.arm
	b MonException

	b MonException

	b MonException

	b MonException

@ Entry points for the overlays: their functions return through MonEntryCommandDone
@ with lr = MonEntryCommandLoop.
MonEntryCommandLoop:
	.thumb
	b MonCommandLoop

MonEntryCommandDone:
	b MonCommandDone

@ Return to the game: WAITCNT = r0, then r0 and r1 of MonSavedRegisters and bx lr.
MonResume:
	ldr r1, RomTail_09FE2090
	strh r0, [r1]
	ldr r1, RomTail_09FE201C
	bx r1

RomTail_09FE201C:
	.4byte MonResume_Arm - RES

MonResume_Arm:
	.arm
	mov r0, #0
	ldr r1, RomTail_09FE208C
	strh r0, [r1, #0x12]
	ldr r0, RomTail_09FE2084
	ldr r1, [r0, #4]
	ldr r0, [r0]
	bx lr

	mov r0, r0

@ Exception entry: saves r0-r3 and WAITCNT, sets WAITCNT to 0, then MonException_Arm.
MonException:
	mov ip, r0
	ldr r0, RomTail_09FE204C
	bx r0

RomTail_09FE204C:
	.4byte MonException_Thumb - RES + 1

MonException_Thumb:
	.thumb
	ldr r0, RomTail_09FE208C
	str r2, [r0, #0x28]
	str r1, [r0, #0x24]
	ldr r0, RomTail_09FE2090
	ldrh r2, [r0]
	movs r1, #0
	strh r1, [r0]
	b RomTail_09FE2434

@ Sets bit 15 of the state (MonCommandBlock + 0x12), waits until the host has cleared the
@ done flag and has written a command, then runs it.
MonCommandLoop:
	ldrh r1, [r0, #0x12]
	ldr r2, RomTail_09FE2270
	orrs r1, r2
	strh r1, [r0, #0x12]

RomTail_09FE2068:
	ldrh r1, [r0, #0x10]
	cmp r1, #0
	bne RomTail_09FE2068

RomTail_09FE206E:
	ldrh r1, [r0]
	cmp r1, #0
	beq RomTail_09FE206E
	ldr r1, RomTail_09FE226C
	bx r1

@ Done flag = 1, command = 0.
MonCommandDone:
	movs r1, #1
	strh r1, [r0, #0x10]
	movs r1, #0
	strh r1, [r0]
	bx lr

	.align 2, 0
