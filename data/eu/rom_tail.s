	.byte 0x01
	.space 11
	.4byte 0x00000001, 0x089374DC
	.space 20
	.4byte 0x0000001F, 0x04000000, 0x03007EDC, 0x0000034C
	.4byte 0x0000034C, 0x6000001F, 0x03007FA0, 0x00000350
	.4byte 0x6000001F, 0x03007FD0, 0x0805C548, 0x6000003F
	.space 8
	.4byte 0xC0000036, 0x000045B7
	.byte 0x54
	.space 19

